// Each glyph as GLYPH_H rows of GLYPH_W bits, the leftmost pixel the highest bit.
export const GLYPHS: ReadonlyMap<string, readonly number[]> = new Map(
  Object.entries(ROWS).map(([ch, rows]) => {
    const bits = rows.split("|").map(r => [...r].reduce((v, c) => (v << 1) | (c === "#" ? 1 : 0), 0));
    while (bits.length < GLYPH_H) bits.push(0);
    return [ch, bits];
  })
);
